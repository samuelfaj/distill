#[derive(Debug)]
struct FixedClock(i64);

impl V2Clock for FixedClock {
    fn now_unix_seconds(&self) -> i64 {
        self.0
    }
}

struct Fixture {
    _temp: TempDir,
    source: PathBuf,
    global: PathBuf,
    workspace: PathBuf,
    policy: V2MemoryAccessPolicy,
}

impl Fixture {
    fn new() -> Self {
        let temp = TempDir::new().unwrap();
        let root = temp.path().join("memory-v2");
        let legacy_root = temp.path().join("memory");
        let global = root.join("global");
        let workspace = root.join("workspaces/repo-50aa78f0");
        fs::create_dir_all(&root).unwrap();
        fs::create_dir_all(legacy_root.join("repo-50aa78f0")).unwrap();
        ensure_scope_initialized(&root, &global, V2MemoryScope::Global).unwrap();
        ensure_scope_initialized(&root, &workspace, V2MemoryScope::Workspace).unwrap();
        let policy = V2MemoryAccessPolicy::new(&global, &workspace).unwrap();
        Self {
            _temp: temp,
            source: legacy_memory_file(&legacy_root, V2MemoryScope::Workspace, "repo-50aa78f0"),
            global,
            workspace,
            policy,
        }
    }

    fn write_legacy(&self, content: &str) {
        fs::write(&self.source, content).unwrap();
    }

    fn run(&self) -> Result<V2CarryoverOutcome> {
        carry_over_legacy_memory(
            &self.workspace,
            &self.source,
            &self.policy,
            &FixedClock(1_760_000_000),
        )
    }

    fn run_imported(&self) -> V2CarryoverReport {
        match self.run().unwrap() {
            V2CarryoverOutcome::Imported(report) => report,
            other => panic!("expected import, got {other:?}"),
        }
    }

    fn topic(&self, slug: &str) -> String {
        fs::read_to_string(self.workspace.join(format!("topics/{slug}.md"))).unwrap()
    }

    fn topic_names(&self) -> Vec<String> {
        let mut names: Vec<String> = fs::read_dir(self.workspace.join("topics"))
            .unwrap()
            .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        names.sort();
        names
    }

    fn meta(&self, key: &str) -> Option<String> {
        let path = self.workspace.join("memory_state.sqlite");
        let connection = JournalMode::for_db_path(&path).open(&path).unwrap();
        connection
            .query_row(
                "SELECT value FROM meta WHERE key = ?1",
                params![key],
                |row| row.get(0),
            )
            .ok()
    }

    fn manifest(&self) -> crate::v2::V2Manifest {
        render_scope_manifest(
            &self.workspace,
            V2MemoryScope::Workspace,
            V2ManifestBudget::default(),
        )
        .unwrap()
    }
}

