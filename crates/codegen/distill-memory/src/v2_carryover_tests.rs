#[test]
fn sections_beyond_the_cap_fold_into_one_topic_and_the_index_stays_bounded() {
    let fixture = Fixture::new();
    let mut content = String::from("# Project Memory — repo\n\n");
    for index in 0..40 {
        content.push_str(&format!(
            "## Topic {index}\n\nFact number {index} about the project.\n\n### Detail\n\nMore on {index}.\n\n"
        ));
    }
    fixture.write_legacy(&content);

    assert_eq!(25, fixture.run_imported().topics_created);
    let folded = fixture.topic("more-notes");
    assert!(folded.starts_with("# More notes\n"));
    assert!(folded.contains("\n## Topic 24\n\nFact number 24 about the project.\n\n### Detail\n"));
    assert!(folded.contains("\n## Topic 39\n"));
    let manifest = fixture.manifest();
    assert_eq!(25, manifest.included_entries);
    assert!(!manifest.is_truncated);
}

