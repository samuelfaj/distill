#[test]
fn tombstoned_topic_name_is_not_recreated() {
    let fixture = Fixture::new();
    let path = fixture.workspace.join("topics/build-test.md");
    fs::write(&path, "# Build & Test\nOld.\n").unwrap();
    V2MaintenanceStore::open_with_clock(
        &fixture.workspace,
        V2MemoryScope::Workspace,
        &fixture.global,
        &fixture.workspace,
        std::sync::Arc::new(FixedClock(1)),
    )
    .unwrap()
    .forget(&ForgetRequest {
        relative_path: PathBuf::from("topics/build-test.md"),
        expected_content_hash: blake3::hash(b"# Build & Test\nOld.\n").to_hex().to_string(),
        reason: ForgetReason::UserRequest,
        now: 1,
    })
    .unwrap();
    fixture.write_legacy(DREAM_SHAPED);

    let report = fixture.run_imported();
    assert_eq!((1, 1), (report.topics_created, report.sections_skipped));
    assert!(!path.exists());
    assert!(
        fixture.meta(META_HASH_KEY).is_some(),
        "a tombstone is a deterministic skip, so the import is complete"
    );
    assert_eq!(V2CarryoverOutcome::Unchanged, fixture.run().unwrap());
}

