#[test]
fn write_failure_leaves_the_hash_unrecorded_so_the_next_start_retries() {
    let fixture = Fixture::new();
    fixture.write_legacy(DREAM_SHAPED);
    // A directory where the topic file belongs fails the read and the write
    // for any user, unlike a permission bit, which root ignores.
    let blocker = fixture.workspace.join("topics/build-test.md");
    fs::create_dir(&blocker).unwrap();

    let report = fixture.run_imported();
    assert_eq!((1, 1), (report.topics_created, report.sections_skipped));
    assert_eq!(
        None,
        fixture.meta(META_HASH_KEY),
        "a write error must not finalize"
    );

    fs::remove_dir(&blocker).unwrap();
    let report = fixture.run_imported();
    assert_eq!(
        (1, 1),
        (report.topics_created, report.sections_skipped),
        "retry writes the failed section and skips the one already present"
    );
    assert!(fixture.meta(META_HASH_KEY).is_some());
    assert_eq!(V2CarryoverOutcome::Unchanged, fixture.run().unwrap());
}

