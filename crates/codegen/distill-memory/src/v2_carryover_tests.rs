#[test]
fn dream_shaped_file_splits_into_one_topic_per_section() {
    let fixture = Fixture::new();
    fixture.write_legacy(DREAM_SHAPED);

    let report = fixture.run_imported();
    assert_eq!(
        V2CarryoverReport {
            topics_created: 2,
            topics_appended: 0,
            sections_skipped: 0,
            bytes_written: (fixture.topic("identity-and-pr-lookup").len()
                + fixture.topic("build-test").len()) as u64,
        },
        report
    );
    assert_eq!(
        "# Identity and PR lookup\nThe reviewer bot's login is `review-bot`.\n\n\
         The reviewer bot's login is `review-bot`. A name search does not find its PRs.\n\n\
         ## Query\n\nUse `author:review-bot` on `org/repo`.\n",
        fixture.topic("identity-and-pr-lookup")
    );
    let build = fixture.topic("build-test");
    assert!(build.starts_with("# Build & Test\nRun `cargo test -p distill-memory`.\n\n"));
    assert!(
        build.contains("\n# not a heading\n"),
        "fenced text is copied verbatim"
    );
    assert_eq!(DREAM_SHAPED, fs::read_to_string(&fixture.source).unwrap());
    assert_eq!(
        Some(blake3::hash(DREAM_SHAPED.as_bytes()).to_hex().to_string()),
        fixture.meta(META_HASH_KEY)
    );
    assert_eq!(Some("1760000000".to_owned()), fixture.meta(META_AT_KEY));
    assert!(fixture.manifest().content.contains(
        "- **Identity and PR lookup** — The reviewer bot's login is 'review-bot'. (`topics/identity-and-pr-lookup.md`)"
    ));
}

#[test]
fn unchanged_source_is_a_no_op_and_a_changed_source_imports_only_the_delta() {
    let fixture = Fixture::new();
    fixture.write_legacy(DREAM_SHAPED);
    fixture.run_imported();
    let first = fixture.topic("build-test");

    assert_eq!(V2CarryoverOutcome::Unchanged, fixture.run().unwrap());
    assert_eq!(first, fixture.topic("build-test"));

    fixture.write_legacy(&format!(
        "{DREAM_SHAPED}\n## Build & Test\n\nAlso run `cargo fmt --all`.\n\n## Releases\n\nAlpha is `grok update --alpha`.\n"
    ));
    let report = fixture.run_imported();
    assert_eq!(1, report.topics_created, "Releases is new");
    assert_eq!(1, report.topics_appended, "Build & Test gained a paragraph");
    assert_eq!(1, report.sections_skipped, "Identity is present verbatim");
    let build = fixture.topic("build-test");
    assert!(build.starts_with(first.trim_end()));
    assert!(build.ends_with("\n\n## From earlier sessions\n\nAlso run `cargo fmt --all`.\n"));
    assert_eq!(
        vec!["build-test.md", "identity-and-pr-lookup.md", "releases.md"],
        fixture.topic_names()
    );
}

#[test]
fn existing_v2_topic_keeps_its_content_first_and_demotes_appended_headings() {
    let fixture = Fixture::new();
    let existing = "# Build & Test\nHow the crate is built.\n\n## Commands\n- `cargo test`\n";
    fs::write(fixture.workspace.join("topics/build-test.md"), existing).unwrap();
    fixture.write_legacy(DREAM_SHAPED);

    let report = fixture.run_imported();
    assert_eq!((1, 1), (report.topics_created, report.topics_appended));
    let merged = fixture.topic("build-test");
    let appended = merged
        .strip_prefix(existing.trim_end())
        .expect("existing content stays first");
    assert!(
        appended
            .starts_with("\n\n## From earlier sessions\n\nRun `cargo test -p distill-memory`.")
    );
    assert_eq!(
        1,
        appended.matches("\n## ").count(),
        "appended headings sit below the section heading"
    );
}

