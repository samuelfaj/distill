#[test]
fn missing_or_scaffold_sources_leave_the_scope_untouched() {
    let fixture = Fixture::new();
    assert_eq!(V2CarryoverOutcome::MissingSource, fixture.run().unwrap());

    fixture.write_legacy(
        "# Project Memory — repo\n\n> Auto-populated by dream consolidation. Edit freely.\n",
    );
    assert_eq!(V2CarryoverOutcome::NothingToCarry, fixture.run().unwrap());
    fixture.write_legacy(
        "# Global Memory\n\n> managed\n\n## Preferences\n\n<!-- Add any cross-project preferences here -->\n",
    );
    assert_eq!(V2CarryoverOutcome::NothingToCarry, fixture.run().unwrap());

    assert!(fixture.topic_names().is_empty());
    assert_eq!(None, fixture.meta(META_HASH_KEY));
}

